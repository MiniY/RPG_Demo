[CmdletBinding()]
param()
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
$config=Get-Content -LiteralPath (Join-Path $PSScriptRoot 'config.json') -Raw|ConvertFrom-Json
$root=[IO.Path]::GetFullPath($config.outputRoot)
$center=Join-Path $root '00_测试中心'
$trendDir=Join-Path $root '04_性能基准与趋势'
$bugsDir=Join-Path $root '06_缺陷追踪'
$rawDir=Join-Path $root '07_测试证据与原始日志'
foreach($d in @($center,$trendDir,$bugsDir,$rawDir)){[IO.Directory]::CreateDirectory($d)|Out-Null}
$marker='<!-- DATATEST_GENERATED: DO NOT EDIT; generated by Update-DataTestDashboard.ps1 -->'
$page=Join-Path $center 'DataTest-自动状态.md'
if(Test-Path -LiteralPath $page){
 if((Get-Content -LiteralPath $page -TotalCount 1) -ne $marker){throw 'Dashboard lacks generated marker; refuse overwrite.'}
}
$syncPath=Join-Path $root '01_环境与同步\sync-status.json'
$sync=if(Test-Path -LiteralPath $syncPath){Get-Content -LiteralPath $syncPath -Raw|ConvertFrom-Json}else{$null}
$runs=@()
foreach($f in @(Get-ChildItem -LiteralPath $rawDir -Filter 'summary.json' -Recurse -File -ErrorAction SilentlyContinue)){
 try{$runs+=Get-Content -LiteralPath $f.FullName -Raw|ConvertFrom-Json}catch{}
}
$runs=@($runs|Sort-Object startedAt -Descending)
$latest=if($runs.Count){$runs[0]}else{$null}
$latestMainPass=@($runs|Where-Object {$sync -and $_.mainSha -eq $sync.mainSha -and $_.status -eq 'PASS'}|Select-Object -First 1)
$bugs=@(Get-ChildItem -LiteralPath $bugsDir -Filter 'BUG-*.md' -File -ErrorAction SilentlyContinue)
$openBugs=0
foreach($f in $bugs){
 $line=Get-Content -LiteralPath $f.FullName|Where-Object {$_ -match '^- 状态：'}|Select-Object -First 1
 if($line -notmatch 'VERIFIED|CLOSED'){$openBugs++}
}
$rows=@()
foreach($run in $runs){
 foreach($leg in @($run.legs)){
  if(-not $leg){continue}
  if(-not $leg.metrics -or -not(Test-Path -LiteralPath $leg.metrics)){continue}
  try{
   $m=Get-Content -LiteralPath $leg.metrics -Raw|ConvertFrom-Json
   $rows+=[pscustomobject]@{runId=$run.runId;startedAt=$run.startedAt;profile=$run.profile;status=$run.status;mainSha=$run.mainSha;dataTestSha=$run.dataTestSha;loops=$m.loops;meanMilliseconds=$m.meanMilliseconds;p95Milliseconds=$m.p95Milliseconds;p99Milliseconds=$m.p99Milliseconds;managedBeforeBytes=$m.managedBeforeBytes;managedAfterBytes=$m.managedAfterBytes;unityReservedBeforeBytes=$m.unityReservedBeforeBytes;unityReservedAfterBytes=$m.unityReservedAfterBytes}
  }catch{}
 }
}
$trend=Join-Path $trendDir 'map-generator-trend.csv'
$rows|Sort-Object startedAt|Export-Csv -LiteralPath $trend -NoTypeInformation -Encoding UTF8
$baseline=@($rows|Where-Object {$_.profile -eq 'Performance' -and $_.status -eq 'PASS'}|Sort-Object startedAt|Select-Object -First 1)
$lines=@($marker,'# RPG_Demo DataTest 自动状态','','此页由运行器生成；精确证据以各 Run ID 的 XML、JSON 和 Unity 日志为准。','','## 同步','')
if($sync){
 $lines+=@("- 最近检查：$($sync.checkedAt)","- 结果：**$($sync.result)**；最近成功：$($sync.lastSuccessfulSyncAt)","- main SHA：$($sync.mainSha)","- DataTest SHA：$($sync.dataTestSha)；待同步提交：$($sync.pendingCommits)","- 冲突：$($sync.conflict)；错误：$($sync.error)")
}else{$lines+='- 尚无同步状态。'}
$lines+=@('','## 最新 main 是否已测试','')
if($sync -and $latestMainPass.Count){
 $lines+="- 已有 **PASS** 记录：[$($latestMainPass[0].runId)](../03_测试运行报告/$($latestMainPass[0].runId).md)；仅覆盖该次运行报告列出的范围。"
}else{$lines+='- 尚无针对最新 main SHA 的完整 PASS 运行。'}
$lines+=@('','## 最新测试','')
if($latest){
 $lines+=@("- [$($latest.runId)](../03_测试运行报告/$($latest.runId).md)：**$($latest.status)**，$($latest.profile)，main $($latest.mainSha)","- NUnit：总数 $($latest.counts.total)，通过 $($latest.counts.passed)，失败 $($latest.counts.failed)；原因：$($latest.reason)")
}else{$lines+='- 尚无测试运行。'}
$lines+=@('','## 性能与缺陷','')
if($baseline.Count){
 $b=$baseline[0]
 $lines+="- 首个完整 Performance Baseline：$($b.runId)，平均 $([math]::Round($b.meanMilliseconds,2)) ms，P95 $([math]::Round($b.p95Milliseconds,2)) ms。"
}else{$lines+='- 完整 Performance Baseline：尚未建立；不能判断性能回归。'}
$lines+=@('','## 高风险与未覆盖','','- 高风险：Editor 批处理在两次 Performance 运行中写出 NUnit XML 后退出超时；性能样本暂不作为可靠基线。','- 未覆盖：Windows Player 构建与启动、真实玩家输入黑盒、战斗和背包商店全链路、长期场景资源生命周期。','- 性能退化：目前无完整 Performance 基线及后续有效样本，无法判定。')
$lines+=@("- 指标历史：[map-generator-trend.csv](../04_性能基准与趋势/map-generator-trend.csv)（含 BLOCKED 样本，比较时按状态过滤）。","- 未关闭 Bug 记录：$openBugs。未发现不等于没有 Bug。",'- 内存泄漏结论：尚无跨进程长期证据；短循环数据只作为线索。','','## 最近运行','','| Run ID | 模式 | 状态 | main SHA | NUnit 通过/总数 |','| --- | --- | --- | --- | --- |')
foreach($run in @($runs|Select-Object -First 10)){
 $lines+="| [$($run.runId)](../03_测试运行报告/$($run.runId).md) | $($run.profile) | $($run.status) | $($run.mainSha) | $($run.counts.passed)/$($run.counts.total) |"
}
$lines+=@('','## 导航','','- [环境审计](../01_环境与同步/环境审计-2026-10-14.md)','- [首轮覆盖矩阵](../02_测试计划与用例/首轮覆盖矩阵-2026-10-14.md)','- [零基础使用教程](../08_操作手册/RPG_Demo%20DataTest%20测试系统零基础使用教程.md)')
$lines|Set-Content -LiteralPath $page -Encoding UTF8
Write-Output $page

