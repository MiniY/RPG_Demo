using System;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEngine;

/// <summary>Builds the isolated Monster ecology acceptance Player from the real SampleScene.</summary>
public static class MapAcceptanceBuild
{
    [Serializable] private sealed class PlayerBuildEvidence
    {
        public string result, path, unity, scene;
        public int errors, warnings;
        public ulong bytes;
        public bool development;
        public string[] defines, packedSourceAssets;
    }
    [Serializable] private sealed class BuildSourceSideEffect
    {
        public string path, beforeSha256, generatedSha256, restoredSha256;
        public string scope = "TMP clears its dynamic glyph/atlas cache during Build. Preserve generated bytes as evidence, then restore the exact pre-build source; no cache delta is adopted.";
    }
    private static string Digest(byte[] bytes)
    {
        using (var sha = System.Security.Cryptography.SHA256.Create())
            return BitConverter.ToString(sha.ComputeHash(bytes)).Replace("-", "").ToLowerInvariant();
    }
